import React from 'react';
import { CheckCircle2, Printer, Download, ShieldAlert, X } from 'lucide-react';
import { CommonReceiptData } from '../types';
import { Language } from '../translations';

interface ReceiptViewProps {
  receipt: CommonReceiptData;
  language: Language;
  onClose?: () => void;
  actionButtonLabel?: string;
  onSecondaryAction?: () => void;
}

export const ReceiptView: React.FC<ReceiptViewProps> = ({
  receipt,
  language,
  onClose,
  actionButtonLabel,
  onSecondaryAction
}) => {
  // Security & integrity rule: never generate an official receipt unless payment status is verified
  if (receipt.paymentStatus !== 'verified') {
    return (
      <div
        style={{
          backgroundColor: '#FFFDF5',
          border: '2px solid #D97706',
          borderRadius: 'var(--radius-xl)',
          padding: '24px',
          textAlign: 'center',
          boxShadow: 'var(--shadow-md)'
        }}
      >
        <ShieldAlert size={36} color="#B45309" style={{ margin: '0 auto 10px auto' }} />
        <h3 style={{ fontSize: '1.1rem', color: 'var(--color-temple-brown)', marginBottom: '6px' }}>
          {language === 'ta'
            ? 'சரிபார்க்கப்பட்ட கட்டணத்திற்குப் பிறகே ரசீது வழங்கப்படும்'
            : 'Receipt Unavailable Until Payment Is Verified'}
        </h3>
        <p style={{ fontSize: '0.86rem', color: 'var(--color-text-secondary)', marginBottom: '16px' }}>
          {language === 'ta'
            ? `தற்போதைய கட்டண நிலை: ${receipt.paymentStatus.toUpperCase()}.`
            : `Current payment status is "${receipt.paymentStatus.toUpperCase()}". Official receipts are generated only after verified payment.`}
        </p>
        {onClose && (
          <button onClick={onClose} className="btn-temple-secondary" style={{ fontSize: '0.85rem' }}>
            {language === 'ta' ? 'மூடுக' : 'Close'}
          </button>
        )}
      </div>
    );
  }

  const handleDownloadPrintableCopy = () => {
    const esc = (s: string | undefined) =>
      String(s ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');

    const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>Receipt ${esc(receipt.receiptNumber)} - Mouna Gurunathar Temple</title>
<style>
  body { font-family: Arial, sans-serif; background: #FFFDF5; color: #3E2114; padding: 32px; }
  .card { max-width: 680px; margin: 0 auto; background: #FFFFFF; border: 2px solid #6D3518; border-radius: 12px; padding: 28px; }
  .header { text-align: center; border-bottom: 2px solid #C89624; padding-bottom: 14px; margin-bottom: 18px; }
  .badge { display: inline-block; background: #EAF7EE; color: #1B7A3C; border: 1px solid #1B7A3C; padding: 4px 12px; border-radius: 14px; font-size: 12px; font-weight: bold; }
  .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 14px; background: #FFFDF5; border: 1px solid #C89624; border-radius: 8px; padding: 16px; }
  .label { font-size: 11px; color: #58331E; font-weight: bold; text-transform: uppercase; }
  .val { font-size: 15px; font-weight: bold; margin-top: 2px; }
  .demo { margin-top: 16px; padding: 10px; background: #FEF3C7; border: 1px solid #D97706; font-size: 12px; color: #78350F; border-radius: 6px; }
</style>
</head>
<body>
  <div class="card">
    <div class="header">
      <h1 style="margin:0;color:#6D3518;">MOUNA GURUNATHAR TEMPLE</h1>
      <p style="margin:4px 0 10px 0;color:#58331E;">Arul Tharum Muneeswaran • Official-Format Seva & Donation Receipt</p>
      <span class="badge">VERIFIED PAYMENT STATUS (PROTOTYPE DEMO)</span>
    </div>
    <div class="grid">
      <div><div class="label">Receipt Number</div><div class="val">${esc(receipt.receiptNumber)}</div></div>
      <div><div class="label">Payment Reference</div><div class="val">${esc(receipt.paymentReference)}</div></div>
      <div><div class="label">Devotee Name</div><div class="val">${esc(receipt.devoteeName)}</div></div>
      <div><div class="label">Date</div><div class="val">${esc(receipt.date)}</div></div>
      <div><div class="label">Payment Purpose</div><div class="val">${esc(receipt.purpose)}</div></div>
      <div><div class="label">Amount</div><div class="val" style="color:#1B7A3C;">₹${receipt.amount.toLocaleString('en-IN')}</div></div>
    </div>
    ${receipt.extraNote ? `<p style="margin-top:14px;font-size:13px;"><strong>Note:</strong> ${esc(receipt.extraNote)}</p>` : ''}
    <div class="demo">PROTOTYPE DEMONSTRATION RECEIPT: Generated by the frontend prototype after simulated verification. Not an official tax or financial receipt without backend payment gateway integration.</div>
  </div>
</body>
</html>`;
    const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${receipt.receiptNumber}-Mouna-Gurunathar-Receipt.html`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div
      className="printable-receipt"
      style={{
        backgroundColor: '#FFFFFF',
        border: '2px solid var(--color-temple-brown)',
        borderRadius: 'var(--radius-xl)',
        padding: '24px 20px',
        boxShadow: 'var(--shadow-lg)',
        position: 'relative'
      }}
    >
      {onClose && (
        <button
          onClick={onClose}
          className="no-print"
          aria-label="Close receipt"
          style={{
            position: 'absolute',
            top: '14px',
            right: '14px',
            width: '32px',
            height: '32px',
            borderRadius: '50%',
            backgroundColor: 'var(--color-section-bg)',
            border: '1px solid var(--color-border-gold)',
            color: 'var(--color-temple-brown)',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center'
          }}
        >
          <X size={16} />
        </button>
      )}

      {/* Receipt Header */}
      <div
        style={{
          textAlign: 'center',
          borderBottom: '2px solid var(--color-border-gold)',
          paddingBottom: '16px',
          marginBottom: '18px'
        }}
      >
        <div
          style={{
            width: '52px',
            height: '52px',
            margin: '0 auto 8px auto',
            borderRadius: '50%',
            backgroundColor: 'var(--color-temple-brown)',
            border: '2px solid var(--color-gold-bright)',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'center',
            color: '#FFD54F',
            fontSize: '22px',
            fontWeight: 800
          }}
        >
          ॐ
        </div>

        <h3
          style={{
            fontFamily: 'var(--font-heading)',
            fontSize: 'clamp(1.1rem, 2.8vw, 1.4rem)',
            color: 'var(--color-temple-brown)',
            fontWeight: 800
          }}
        >
          {language === 'ta' ? 'மௌன குருநாதர் திருக்கோயில்' : 'MOUNA GURUNATHAR TEMPLE'}
        </h3>
        <p style={{ color: 'var(--color-text-secondary)', fontSize: '0.84rem', fontWeight: 600 }}>
          {language === 'ta'
            ? 'நன்கொடை & அன்னதான பொது ரசீது (மாதிரி)'
            : 'Unified Donation & Annadhanam Receipt'}
        </p>

        <div
          style={{
            display: 'inline-flex',
            alignItems: 'center',
            gap: '6px',
            backgroundColor: '#EAF7EE',
            color: '#1B7A3C',
            border: '1px solid #38A169',
            padding: '4px 14px',
            borderRadius: '16px',
            fontSize: '0.75rem',
            fontWeight: 800,
            marginTop: '10px'
          }}
        >
          <CheckCircle2 size={14} />
          <span>
            {language === 'ta'
              ? 'சரிபார்க்கப்பட்ட கட்டண நிலை (மாதிரி)'
              : 'VERIFIED PAYMENT STATUS (DEMO PROTOTYPE)'}
          </span>
        </div>
      </div>

      {/* Receipt Details Grid */}
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'repeat(auto-fit, minmax(min(100%, 190px), 1fr))',
          gap: '14px',
          backgroundColor: '#FFFDF5',
          border: '1.5px solid var(--color-border-gold)',
          borderRadius: 'var(--radius-md)',
          padding: '16px',
          marginBottom: '16px'
        }}
      >
        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'ரசீது எண்:' : 'RECEIPT NUMBER:'}
          </span>
          <span style={{ fontSize: '1rem', fontWeight: 900, color: 'var(--color-temple-brown)', wordBreak: 'break-all' }}>
            {receipt.receiptNumber}
          </span>
        </div>

        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'கட்டணக் குறிப்பு எண்:' : 'PAYMENT REFERENCE:'}
          </span>
          <span style={{ fontSize: '0.92rem', fontWeight: 800, color: 'var(--color-text-main)', wordBreak: 'break-all' }}>
            {receipt.paymentReference}
          </span>
        </div>

        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'பக்தர் பெயர்:' : 'DEVOTEE NAME:'}
          </span>
          <span style={{ fontSize: '0.95rem', fontWeight: 800, color: 'var(--color-text-main)' }}>
            {receipt.devoteeName}
          </span>
        </div>

        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'கட்டண நோக்கம்:' : 'PAYMENT PURPOSE:'}
          </span>
          <span style={{ fontSize: '0.92rem', fontWeight: 800, color: 'var(--color-temple-brown)' }}>
            {receipt.purpose}
          </span>
        </div>

        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'தொகை:' : 'AMOUNT:'}
          </span>
          <span style={{ fontSize: '1.22rem', fontWeight: 900, color: '#1B7A3C' }}>
            ₹{receipt.amount.toLocaleString('en-IN')}
          </span>
        </div>

        <div>
          <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
            {language === 'ta' ? 'தேதி:' : 'DATE:'}
          </span>
          <span style={{ fontSize: '0.92rem', fontWeight: 800, color: 'var(--color-text-main)' }}>
            {receipt.date}
          </span>
        </div>

        {receipt.extraNote && (
          <div style={{ gridColumn: '1 / -1' }}>
            <span style={{ fontSize: '0.7rem', color: 'var(--color-text-secondary)', fontWeight: 700, display: 'block' }}>
              {language === 'ta' ? 'குறிப்பு / அர்ப்பணிப்பு:' : 'DEDICATION / NOTE:'}
            </span>
            <span style={{ fontSize: '0.86rem', color: 'var(--color-text-main)', fontStyle: 'italic' }}>
              "{receipt.extraNote}"
            </span>
          </div>
        )}
      </div>

      {/* Prototype Honesty Notice */}
      <div
        style={{
          backgroundColor: '#FEF3C7',
          border: '1px solid #D97706',
          borderRadius: 'var(--radius-sm)',
          padding: '10px 12px',
          fontSize: '0.76rem',
          color: '#78350F',
          lineHeight: 1.45,
          marginBottom: '16px'
        }}
      >
        <strong>{language === 'ta' ? 'முன்மாதிரி அறிவிப்பு:' : 'PROTOTYPE DEMONSTRATION NOTICE:'}</strong>{' '}
        {language === 'ta'
          ? 'இது முன்மாதிரி செயல்முறை ரசீது மட்டுமே. உண்மையான நிதி பரிவர்த்தனைக்கு பாதுகாப்பான பின்புல கட்டண நுழைவாயில் இணைக்கப்பட வேண்டும். தனிப்பட்ட ரசீது தகவல்கள் பொதுவில் காட்டப்படுவதில்லை.'
          : 'Generated by frontend demonstration mode. Real payment verification and official receipts require secure backend gateway integration. Private devotee records are restricted.'}
      </div>

      {/* Actions */}
      <div className="no-print" style={{ display: 'flex', gap: '10px', justifyContent: 'center', flexWrap: 'wrap' }}>
        <button
          type="button"
          onClick={() => window.print()}
          className="btn-temple-gold"
          style={{ padding: '9px 18px', fontSize: '0.86rem' }}
        >
          <Printer size={16} />
          <span>{language === 'ta' ? 'அச்சிடு / PDF சேமி' : 'Print / Save as PDF'}</span>
        </button>

        <button
          type="button"
          onClick={handleDownloadPrintableCopy}
          className="btn-temple-secondary"
          style={{ padding: '9px 18px', fontSize: '0.86rem' }}
        >
          <Download size={16} />
          <span>{language === 'ta' ? 'ரசீது கோப்பு பதிவிறக்கு' : 'Download Receipt File'}</span>
        </button>

        {onSecondaryAction && actionButtonLabel && (
          <button
            type="button"
            onClick={onSecondaryAction}
            className="btn-temple-primary"
            style={{ padding: '9px 18px', fontSize: '0.86rem' }}
          >
            <span>{actionButtonLabel}</span>
          </button>
        )}
      </div>
    </div>
  );
};

